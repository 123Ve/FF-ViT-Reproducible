"""Export real ImageNet images for the unchanged E07 model, not a new model.

No model weights, ROM, RTL or FPGA files are generated by this script.
The fixed prefix subset is chosen before any inference result is available.
"""
import argparse
import csv
import hashlib
import io
import json
import struct
import zlib
from pathlib import Path

import numpy as np
from PIL import Image

FRAME_BYTES = 301056
MEAN = np.asarray([.485,.456,.406], dtype=np.float32)[:,None,None]
STD = np.asarray([.229,.224,.225], dtype=np.float32)[:,None,None]


def digest(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream,"sha256").hexdigest()


def pack_normalized_chw(image):
    image = np.asarray(image,dtype=np.float32)
    if image.shape != (3,224,224) or not np.isfinite(image).all():
        raise ValueError("expected finite normalized float32 CHW[3,224,224]")
    q = np.clip(np.rint(image * np.float32(64)), -32768,32767).astype("<i2")
    # logical[patch_y,patch_x,channel,within_y,within_x], row-major patches
    logical = q.reshape(3,14,16,14,16).transpose(1,3,0,2,4).reshape(196,768)
    physical = logical.reshape(98,2,768).transpose(0,2,1)
    return physical.astype("<i2",copy=False).tobytes(order="C")


def pack_jpeg(jpeg):
    with Image.open(io.BytesIO(jpeg)) as raw:
        im = raw.convert("RGB")
        w,h = im.size
        if w <= h:
            ow,oh = 248,int(248*h/w)
        else:
            ow,oh = int(248*w/h),248
        im = im.resize((ow,oh),resample=Image.Resampling.BICUBIC)
        left,top = int(round((ow-224)/2)),int(round((oh-224)/2))
        im = im.crop((left,top,left+224,top+224))
        x = np.asarray(im,dtype=np.float32).transpose(2,0,1)/np.float32(255)
        x = (x-MEAN)/STD
        return pack_normalized_chw(x)


def export_dataset(data,out,*,count=1000,chunk_frames=1000):
    import pyarrow.parquet as pq
    data,out = Path(data),Path(out)
    if not 1 <= count <= 50000 or not 1 <= chunk_frames <= 1000:
        raise ValueError("count must be 1..50000; chunk_frames 1..1000 (FAT32 safe)")
    files = sorted(data.glob("validation-*.parquet"))
    if not files:
        raise FileNotFoundError(f"no validation Parquet files: {data}")
    if sum(pq.ParquetFile(p).metadata.num_rows for p in files) < count:
        raise ValueError("requested more unique images than available")
    out.mkdir(parents=True,exist_ok=False)
    originals = out/"original_images"
    originals.mkdir()
    seen=set()
    distribution={}
    sources=[]
    frame = 0
    chunk = None
    try:
        with (out/"INDEX.BIN").open("xb") as index, (out/"SAMPLES.CSV").open("x",newline="") as mapping:
            index.write(struct.pack("<8s6I",b"IM1KE07\0",1,count,FRAME_BYTES,chunk_frames,12,0))
            writer=csv.writer(mapping)
            writer.writerow(["index","source_parquet","source_row","original_path","label",
                             "image_sha256","input_sha256","input_crc32","chunk","byte_offset"])
            for path in files:
                if frame == count:
                    break
                sources.append({"path":str(path.resolve()),"sha256":digest(path)})
                row=0
                for batch in pq.ParquetFile(path).iter_batches(batch_size=64,columns=["image","label"]):
                    for record in batch.to_pylist():
                        if frame == count:
                            break
                        image=record["image"]
                        label=record["label"]
                        if type(label) is not int or not 0 <= label < 1000:
                            raise ValueError(f"invalid label at {path}:{row}")
                        identity=image["path"]
                        if not identity or identity in seen:
                            raise ValueError(f"duplicate/missing image identity: {identity}")
                        seen.add(identity)
                        jpeg=image["bytes"]
                        payload=pack_jpeg(jpeg)
                        crc=zlib.crc32(payload)
                        if frame % chunk_frames == 0:
                            if chunk:
                                chunk.close()
                            chunk=(out/f"I{frame//chunk_frames:03d}.BIN").open("xb")
                        chunk.write(payload)
                        index.write(struct.pack("<3I",frame,label,crc))
                        (originals/f"V{frame:05d}.JPEG").write_bytes(jpeg)
                        writer.writerow([frame,path.name,row,identity,label,hashlib.sha256(jpeg).hexdigest(),
                            hashlib.sha256(payload).hexdigest(),f"{crc:08x}",f"I{frame//chunk_frames:03d}.BIN",
                            (frame%chunk_frames)*FRAME_BYTES])
                        distribution[label]=distribution.get(label,0)+1
                        frame+=1
                        row+=1
                        if frame % 100 == 0:
                            print(f"EXPORTED={frame}/{count}",flush=True)
                    if frame == count:
                        break
            if frame != count:
                raise RuntimeError("incomplete dataset export")
    finally:
        if chunk:
            chunk.close()
    output_files=[out/"INDEX.BIN",out/"SAMPLES.CSV",*sorted(out.glob("I???.BIN"))]
    manifest={"status":"READY_FOR_BOARD_TEST_NOT_MEASURED","model":"unchanged frozen E07",
        "scope":"cross-dataset evaluation; no ImageNet model parameters loaded",
        "selection":"first N unique rows in sorted validation Parquet shard order; no inference filtering",
        "count":count,"classes_present":len(distribution),"class_counts":distribution,
        "chunk_frames":chunk_frames,"bytes_per_frame":FRAME_BYTES,
        "preprocessing":{"resize_short_side":248,"center_crop":224,"interpolation":"PIL bicubic",
            "mean":[.485,.456,.406],"std":[.229,.224,.225],"input_scale":1/64,
            "rounding":"nearest ties-to-even","dtype":"little-endian signed int16",
            "logical_layout":"[196,768] channel/patch_y/patch_x within each patch",
            "dma_layout":"[98,768,2] token-pair interleaved; no token omitted at input"},
        "sources":sources,"files":{p.name:{"bytes":p.stat().st_size,"sha256":digest(p)} for p in output_files}}
    (out/"dataset_identity.json").write_text(json.dumps(manifest,indent=2)+"\n")
    return manifest


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data",type=Path,default=Path("/home/user/Desktop/ff_vit_re/imagenet_val/data"))
    parser.add_argument("--out",type=Path,default=Path(__file__).resolve().parent/"deploy")
    parser.add_argument("--count",type=int,default=1000)
    parser.add_argument("--chunk-frames",type=int,default=1000)
    args=parser.parse_args()
    result=export_dataset(args.data,args.out,count=args.count,chunk_frames=args.chunk_frames)
    print(f"DATASET_READY frames={result['count']} classes={result['classes_present']}")
