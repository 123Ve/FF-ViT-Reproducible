#!/usr/bin/env python3
"""
Stage 4K2: refine Q/K/V requant LUTs and isolate where the Stage-4K
accuracy loss comes from.

This stage reuses the exact LN1 parameters already generated by Stage 4K.
It then evaluates, in order:

  1) exact LN1 + Stage4J QKV surrogate
  2) exact QKV integer MAC + IDEAL round/clip signed-int3 requant
  3) exact Q-only / K-only / V-only refined quant.h LUT
  4) exact Q/K/V refined quant.h LUT together
  5) + exact O projection

The refined LUT search is threshold-centered rather than xmin-centered.
The Stage4J target signed-int3 quantizer saturates the tails, so the useful
address range should be aligned to the transition region between output
codes instead of wasting LUT addresses on saturated accumulator tails.

quant.h address semantics:
    tmp    = (x + b) >> s
    cursor = ap_int<9>(tmp)   # wrap before clamp for Q/K/V
    cursor = clamp(cursor, 0, bound)
    y      = table[cursor]
"""

